"""Rebuild local MiSans subsets. Requires fonttools[woff] (Brotli)."""
from pathlib import Path
from collections import Counter
from fontTools import subset
from fontTools.ttLib import TTFont
import hashlib, json

THEME = Path(__file__).resolve().parents[1]
ROOT = THEME.parents[2]
SOURCE = THEME / 'fonts/MiSans-Normal.woff2'
font = TTFont(SOURCE)
coverage = set(font.getBestCmap())
font.close()
freq = Counter()
for pattern in ('*.php', '*.sql'):
    for path in ROOT.rglob(pattern):
        if pattern == '*.php' and THEME not in path.parents:
            continue
        freq.update(ord(c) for c in path.read_text(encoding='utf-8', errors='ignore') if ord(c) in coverage)
def han(cp):
    return 0x3400 <= cp <= 0x9fff or 0x20000 <= cp <= 0x323af
base = {cp for cp in coverage if cp <= 0x024f or 0x2000 <= cp <= 0x206f or 0x3000 <= cp <= 0x303f or 0xff00 <= cp <= 0xffef}
common = [cp for cp, count in freq.most_common() if han(cp) and cp not in base][:2048]
groups = [('base', sorted(base))]
for i in range(0, len(common), 256):
    groups.append((f'common-{i//256:02}', sorted(common[i:i+256])))
remaining = sorted(coverage - base - set(common))
for i in range(0, len(remaining), 256):
    groups.append((f'extra-{i//256:03}', remaining[i:i+256]))
version = hashlib.sha256(SOURCE.read_bytes()).hexdigest()[:10]
folder = THEME / 'fonts' / f'misans-{version}'
folder.mkdir(exist_ok=True)
def ranges(cps):
    result = []
    start = end = cps[0]
    for cp in cps[1:]:
        if cp == end + 1:
            end = cp
        else:
            result.append(f'U+{start:X}' + (f'-{end:X}' if end != start else ''))
            start = end = cp
    result.append(f'U+{start:X}' + (f'-{end:X}' if end != start else ''))
    return ','.join(result)
css = ['/* Generated by tools/build_misans_subsets.py; all source Unicode characters preserved. */']
records = []
for index, (name, cps) in enumerate(groups):
    output = folder / f'{name}.woff2'
    options = subset.Options()
    options.flavor = 'woff2'
    options.recalc_timestamp = False
    f = subset.load_font(str(SOURCE), options)
    sub = subset.Subsetter(options=options)
    sub.populate(unicodes=cps)
    sub.subset(f)
    subset.save_font(f, str(output), options)
    f.close()
    css.append('@font-face {\n font-family:"NuliBlog MiSans";\n font-style:normal;\n font-weight:400;\n font-display:swap;\n src:url("../fonts/' + folder.name + '/' + output.name + '") format("woff2");\n unicode-range:' + ranges(cps) + ';\n}')
    records.append({'file':output.name, 'characters':len(cps), 'bytes':output.stat().st_size})
    if index % 20 == 0:
        print(f'{index+1}/{len(groups)}', flush=True)
(THEME/'style/misans-subsets.css').write_text('\n'.join(css)+'\n', encoding='utf-8')
(folder/'manifest.json').write_text(json.dumps({'source_sha256':hashlib.sha256(SOURCE.read_bytes()).hexdigest(), 'source_bytes':SOURCE.stat().st_size, 'characters':len(coverage), 'subsets':records}, indent=2), encoding='utf-8')
print(json.dumps({'packs':len(records), 'chars':len(coverage), 'base_bytes':records[0]['bytes'], 'total_bytes':sum(r['bytes'] for r in records), 'folder':str(folder)}), flush=True)
